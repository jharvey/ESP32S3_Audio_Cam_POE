"""Predict the speaker -> mic echo from the board layout (KiCad Python).

usage: python echo_predict.py <board.kicad_pcb> <out_header.h> <out_report.md> [--speaker X,Y] [--depth MM]

Reads the two PDM mics (U16, U17) and where the speaker connects (J10, the speaker header), then works out
for each mic the direct-path distance, delay and level relative to the nearer mic. The speaker itself sits
in the case; by default it is taken to be mounted over its connector, --speaker X,Y (board mm) moves it, and
--depth is how far the speaker cone sits in front of the board (default 8 mm).

The header is used by the simulator's echo model (sim/common/RoomEcho) so each mic gets its own direct path;
the report goes in Docs/. Only the direct path through the case comes from the layout; reflections and the
room's reverb stay with the room presets (classroom, gym).
"""
import math
import sys

import pcbnew

C_MM_PER_MS = 343.0  # speed of sound: 343 m/s = 343 mm/ms
FS = 16000


def main():
    a = sys.argv[1:]
    board, header, report = a[0], a[1], a[2]
    spk_xy = None
    depth = 8.0
    if "--speaker" in a:
        spk_xy = tuple(float(v) for v in a[a.index("--speaker") + 1].split(","))
    if "--depth" in a:
        depth = float(a[a.index("--depth") + 1])
    b = pcbnew.LoadBoard(board)
    mm = pcbnew.ToMM

    def pos(ref):
        f = b.FindFootprintByReference(ref)
        if f is None:
            raise SystemExit("no %s on the board" % ref)
        p = f.GetPosition()
        return mm(p.x), mm(p.y)

    mics = {"U16 (MIC.R)": pos("U16"), "U17 (MIC.L)": pos("U17")}
    conn = pos("J10")
    spk = spk_xy or conn
    rows = []
    for name, (x, y) in mics.items():
        d = math.sqrt((x - spk[0]) ** 2 + (y - spk[1]) ** 2 + depth ** 2)
        rows.append((name, x, y, d))
    dmin = min(r[3] for r in rows)
    out = []
    for name, x, y, d in rows:
        delay_ms = d / C_MM_PER_MS
        rel_db = -20 * math.log10(d / dmin)  # spherical spreading, relative to the nearer mic
        out.append((name, x, y, d, delay_ms, delay_ms * FS / 1000.0, rel_db))
    spacing = math.dist(mics["U16 (MIC.R)"], mics["U17 (MIC.L)"])

    with open(header, "w", newline="\n") as h:
        h.write("// Generated by firmware/tools/echo_predict.py from the board layout. Do not edit.\n")
        h.write("// Direct speaker -> mic path through the case: distance, delay and level (relative to the nearer mic).\n")
        h.write("#pragma once\n\nnamespace sim::board {\n\n")
        h.write("constexpr float kSpeakerX = %.2ff, kSpeakerY = %.2ff, kSpeakerDepth = %.1ff;  // mm\n" % (spk[0], spk[1], depth))
        h.write("constexpr float kMicSpacing = %.2ff;  // mm\n\n" % spacing)
        h.write("struct MicPath { const char* name; float x, y, distMm, delayMs, relDb; };\n")
        h.write("constexpr MicPath kMics[] = {\n")
        for name, x, y, d, dms, ds, rel in out:
            h.write('    {"%s", %.2ff, %.2ff, %.2ff, %.4ff, %.2ff},\n' % (name, x, y, d, dms, rel))
        h.write("};\n\n}  // namespace sim::board\n")

    with open(report, "w", newline="\n") as r:
        r.write("# Echo prediction from the board layout\n\n")
        r.write("Generated by `firmware/tools/echo_predict.py` from `ESP32S3_Audio_Cam_POE.kicad_pcb`.\n\n")
        r.write("Speaker taken at (%.1f, %.1f) mm on the board, %.0f mm in front of it (%s).\n\n"
                % (spk[0], spk[1], depth, "given" if spk_xy else "over its connector J10"))
        r.write("| Mic | Position (mm) | Distance to speaker | Direct-path delay | Level vs nearer mic |\n|---|---|---|---|---|\n")
        for name, x, y, d, dms, ds, rel in out:
            r.write("| %s | %.1f, %.1f | %.1f mm | %.3f ms (%.1f samples) | %+.1f dB |\n" % (name, x, y, d, dms, ds, rel))
        far = min(out, key=lambda o: o[6])
        near = max(out, key=lambda o: o[6])
        alias_hz = C_MM_PER_MS * 1000.0 / (2 * spacing)
        r.write("\nMic spacing: %.1f mm. A two-mic beam only works cleanly below c / (2 x spacing) = %.0f Hz; above that\n"
                "it forms false lobes. So for full-band speech the pair is better used as two mics to choose between (or a\n"
                "low-band beam plus the better mic above %.0f Hz) than as a full-band beamformer. A beam over the whole\n"
                "8 kHz band needs mics at most 21 mm apart.\n\n" % (spacing, alias_hz, alias_hz))
        r.write("What it means:\n\n")
        r.write("- The direct path is well under a millisecond, so it doesn't set the echo canceller's delay: the\n"
                "  I2S and DMA buffering does (measured by auto-tune). The canceller's length is set by the room's reverb.\n")
        r.write("- %s hears the speaker %.1f dB less than %s, so it's the better mic to send from while the speaker\n"
                "  plays, and the beam should null towards the speaker side.\n" % (far[0], abs(far[6] - near[6]), near[0]))
        r.write("- Mounting the speaker in the case away from %s (lower centre, facing the room) cuts the\n"
                "  near mic's echo; this model takes `--speaker X,Y` to compare positions.\n" % near[0].split()[0])
        r.write("- Structure-borne sound through the case and PCB isn't in this model; the case's separate\n"
                "  speaker and mic chambers (roadmap 1.19) are what keep it down.\n")
    for o in out:
        print("%-12s dist %.1f mm  delay %.3f ms  %+.1f dB" % (o[0], o[3], o[4], o[6]))


if __name__ == "__main__":
    main()
